'use strict';
const assert=require('assert');
const A=require('./arnes')(process.argv[2]||'.',{props:{ROL_COMPRAS:'tania@helgen.tech',ROL_REQUISICION:'obrero@helgen.tech',SUPER_ADMIN:'leo@helgen.tech'}});
const {P,ok,falla,plain,HOY_ISO,masDias,PDF,props,libros}=A;
const metodo='Crédito / financiera (proveedor cubierto)';
const pendiente=plain(P.normalizarFinanciamientoProveedor({}));
assert.deepEqual(pendiente,{financiera:'',dias:90,fechaPago:'',vencimiento:'',pendienteConfirmar:true});
assert.throws(()=>P.normalizarFinanciamientoProveedor({dias:-1}),/plazo/);
assert.throws(()=>P.normalizarFinanciamientoProveedor({fechaPago:masDias(1)}),/futura/);
assert.equal(P.normalizarFinanciamientoProveedor({financiera:'Puente',fechaPago:HOY_ISO,dias:90}).vencimiento,masDias(90));
ok('leo','crearProyecto',{nombre:'Proyecto reservado de prueba',ubicacion:'Qro',cliente:{nombre:'Cliente'},idSolicitud:'fin-previo'});
const pry=ok('leo','crearProyecto',{nombre:'Financiamiento prueba',ubicacion:'Qro',cliente:{nombre:'Cliente'},idSolicitud:'fin-p'}).folio;
const req=ok('obrero','guardarRequisicion',{proyectoFolio:pry,renglones:[{descripcion:'Brida',cantidad:1}],cotizacion:{nombre:'c.pdf',datos:PDF},idSolicitud:'fin-r'}).folio;
ok('tania','autorizarRequisicion',req,{proveedor:{razonSocial:'Proveedor'},fechaEntrega:masDias(1),formaPago:'Crédito del proveedor',diasCredito:90,condicionesPago:'90 días',renglones:[{descripcion:'Brida',unidad:'PZA',cantidad:1,costo:100}],idSolicitud:'fin-oc'});
const datos={reqFolio:req,fecha:HOY_ISO,monto:116,monedaPago:'MXN',metodo,referencia:'PORTAL-1',comprobante:{nombre:'p.pdf',datos:PDF},financiamiento:{dias:90},idSolicitud:'fin-pgp'};
const pago=ok('tania','registrarPagoProveedor',datos);
assert(pago.vista.pagos[0].financiamiento.pendienteConfirmar);
assert.equal(ok('tania','registrarPagoProveedor',datos).folio,pago.folio,'reintento no duplica');
falla('tania','registrarPagoProveedor',[{...datos,financiamiento:{dias:60}}],/otro|distinto|mismo|cambi/i);
falla('obrero','editarFinanciamientoProveedor',[pago.folio,{financiera:'X'}],/permiso|compras/i);
const edit=ok('tania','editarFinanciamientoProveedor',pago.folio,{financiera:'Puente',fechaPago:HOY_ISO,dias:90});
assert.equal(edit.pagos[0].financiamiento.vencimiento,masDias(90));
assert.equal(edit.pagos[0].monto,116);
const cxp=ok('tania','cuentasPorPagar');assert.equal(cxp.financiamientos.length,1);assert.equal(cxp.financiamientos[0].monto,116);
const report=ok('tania','reporteCxp');assert.equal(report.totales[0].total,116,'deuda sigue en reportes aunque proveedor quedó cubierto');
ok('tania','cancelarPagoProveedor',pago.folio,'Pago de prueba equivocado');
assert.equal(ok('tania','cuentasPorPagar').financiamientos.length,0);
console.log('OK financiamiento: permisos, persistencia, reintentos, edición y deuda pendiente');
